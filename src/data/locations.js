export function normalizeStr(s) {
  return s.toLowerCase()
    .replace(/ë/g, 'e').replace(/ç/g, 'c').replace(/ä/g, 'a')
    .replace(/ö/g, 'o').replace(/ü/g, 'u').replace(/š/g, 's')
    .replace(/ć/g, 'c').replace(/č/g, 'c').replace(/đ/g, 'd')
    .replace(/ž/g, 'z').replace(/[^a-z0-9 ]/g, '')
}

// Score a location against a query: lower is better, -1 = no match
function matchScore(text, q) {
  const t = normalizeStr(text)
  if (t === q) return 0                 // exact match
  if (t.startsWith(q)) return 1         // starts with query
  const words = t.split(' ')
  if (words.some(w => w.startsWith(q))) return 2  // a word starts with query
  if (t.includes(q)) return 3           // substring match anywhere
  return -1
}

export function searchLocations(query, limit = 8) {
  if (!query || query.length < 2) return []
  const q = normalizeStr(query)

  const scored = []
  for (const loc of KOSOVO_LOCATIONS) {
    let best = matchScore(loc.name, q)
    // Check aliases (Peja, Peć, etc.) - if alias matches, still show under main name
    if (loc.aliases) {
      for (const alias of loc.aliases) {
        const aliasScore = matchScore(alias, q)
        if (aliasScore !== -1 && (best === -1 || aliasScore < best)) {
          best = aliasScore
        }
      }
    }
    // Also check region
    const regionScore = matchScore(loc.region, q)
    if (regionScore !== -1 && (best === -1 || regionScore + 2 < best)) {
      best = regionScore + 2 // region matches ranked slightly lower than name matches
    }
    if (best !== -1) {
      scored.push({ loc, score: best })
    }
  }

  scored.sort((a, b) => a.score - b.score || a.loc.name.length - b.loc.name.length)
  return scored.slice(0, limit).map(s => s.loc)
}

